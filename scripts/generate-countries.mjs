// Regenerates src/lib/countries.generated.ts from libphonenumber-js.
// Run with: node scripts/generate-countries.mjs   (only needed if libphonenumber-js is upgraded;
// a test fails if the generated list drifts from the library)
import { getCountries, getCountryCallingCode } from "libphonenumber-js/min";
import { writeFileSync } from "node:fs";

const DEFAULT = "ZW";
const list = [...getCountries()]
  .sort((a, b) => (a === DEFAULT ? -1 : b === DEFAULT ? 1 : a.localeCompare(b)))
  .map((c) => [c, getCountryCallingCode(c)]);

writeFileSync(
  new URL("../src/lib/countries.generated.ts", import.meta.url),
  `// Generated by scripts/generate-countries.mjs. Do not edit by hand.\n` +
    `// [ISO country code, calling code]; Zimbabwe first, then alphabetical.\n` +
    `export const COUNTRY_CALLING_CODES: readonly (readonly [string, string])[] = ${JSON.stringify(list)};\n`,
);
console.log(`${list.length} countries written.`);
